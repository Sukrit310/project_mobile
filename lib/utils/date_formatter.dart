// จัดรูปแบบวันและเดือนด้วยชื่อภาษาไทย โดยใช้ปีคริสต์ศักราชให้สอดคล้องกันทั้งแอป

const _thaiMonths = [
  'มกราคม',
  'กุมภาพันธ์',
  'มีนาคม',
  'เมษายน',
  'พฤษภาคม',
  'มิถุนายน',
  'กรกฎาคม',
  'สิงหาคม',
  'กันยายน',
  'ตุลาคม',
  'พฤศจิกายน',
  'ธันวาคม',
];

const _shortThaiMonths = [
  'ม.ค.',
  'ก.พ.',
  'มี.ค.',
  'เม.ย.',
  'พ.ค.',
  'มิ.ย.',
  'ก.ค.',
  'ส.ค.',
  'ก.ย.',
  'ต.ค.',
  'พ.ย.',
  'ธ.ค.',
];

/// วันที่ย่อภาษาไทยและปีคริสต์ศักราช เช่น 8 พ.ย. 2026
String formatThaiDate(DateTime date) =>
    '${date.day} ${_shortThaiMonths[date.month - 1]} ${date.year}';

/// ชื่อเดือนเต็มและปี สำหรับหัวข้อและตัวเลือกเดือนของทุกหน้าจอ
String formatThaiMonth(DateTime date) =>
    '${_thaiMonths[date.month - 1]} ${date.year}';
